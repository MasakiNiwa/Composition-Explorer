#!/usr/bin/env node
/**
 * Collects license information for every production dependency and writes:
 *   - public/third-party-licenses.json  (loaded by the About page)
 *   - THIRD_PARTY_NOTICES.md            (committed to the repository)
 *
 * Fails when a dependency uses a license outside ALLOWED (keeps the app
 * MIT-compatible). Run with --check to verify THIRD_PARTY_NOTICES.md is up to date.
 */
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'Python-2.0',
]);

const self = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'));
const out = execSync('npm ls --omit=dev --all --parseable', { cwd: root, encoding: 'utf-8' });
const dirs = [
  ...new Set(
    out
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean),
  ),
].filter((d) => resolve(d) !== root);

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function isAllowed(expr) {
  const parts = expr.replace(/[()]/g, '').split(/\s+(?:OR|AND)\s+/);
  // "OR" expressions only need one allowed option; we conservatively require all for AND.
  if (/\sOR\s/.test(expr)) return parts.some((p) => ALLOWED.has(p));
  return parts.every((p) => ALLOWED.has(p));
}

function repoUrl(pkg) {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (!r) return pkg.homepage ?? '';
  if (/^[\w.-]+\/[\w.-]+$/.test(r)) return `https://github.com/${r}`;
  return r
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/');
}

const seen = new Map();
for (const dir of dirs) {
  const pj = join(dir, 'package.json');
  if (!existsSync(pj)) continue;
  const pkg = JSON.parse(readFileSync(pj, 'utf-8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  const licFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  const noticeFile = readdirSync(dir).find((f) => /^notice(\.|$)/i.test(f));
  const author = typeof pkg.author === 'string' ? pkg.author : (pkg.author?.name ?? '');
  seen.set(key, {
    name: pkg.name,
    version: pkg.version,
    license: licenseOf(pkg),
    author,
    repository: repoUrl(pkg),
    licenseText: licFile ? readFileSync(join(dir, licFile), 'utf-8').trim() : '',
    noticeText: noticeFile ? readFileSync(join(dir, noticeFile), 'utf-8').trim() : '',
  });
}

const packages = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const bad = packages.filter((p) => !isAllowed(p.license));
if (bad.length) {
  console.error(
    'Disallowed or unknown licenses:\n' + bad.map((p) => `  ${p.name}@${p.version}: ${p.license}`).join('\n'),
  );
  process.exit(1);
}

const json = JSON.stringify({ app: self.name, packages }, null, 0);

const md = [
  '# Third-Party Notices',
  '',
  `${self.name} is released under the MIT License (see [LICENSE](LICENSE)).`,
  'It bundles or depends on the following third-party packages at runtime.',
  'This file is generated by `npm run licenses` — do not edit by hand.',
  '',
  '| Package | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.repository} |`),
  '',
  '---',
  '',
  ...packages.flatMap((p) => [
    `## ${p.name}@${p.version}`,
    '',
    `License: ${p.license}${p.author ? `  \nAuthor: ${p.author}` : ''}${p.repository ? `  \nRepository: ${p.repository}` : ''}`,
    '',
    p.licenseText
      ? '```text\n' + p.licenseText.replace(/```/g, "'''") + '\n```'
      : '_No license file included in the package; see the repository._',
    ...(p.noticeText ? ['', 'NOTICE:', '', '```text\n' + p.noticeText.replace(/```/g, "'''") + '\n```'] : []),
    '',
  ]),
].join('\n');

const mdPath = join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  const current = existsSync(mdPath) ? readFileSync(mdPath, 'utf-8') : '';
  if (current !== md) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run `npm run licenses` and commit the result.');
    process.exit(1);
  }
} else {
  writeFileSync(mdPath, md);
}
writeFileSync(join(root, 'public', 'third-party-licenses.json'), json);
console.log(`License data written for ${packages.length} packages.`);
